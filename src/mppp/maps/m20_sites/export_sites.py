"""Write the blocks of rover stations as an MPPP sites file (sites.json version 4 schema).

Load it as notebook 03's SITES_EXTRA, or merge its "sites" and "groups" into src/mppp/data/sites.json.
Each block keeps the MPPP fields (sols, label, zcam, note, no_mask_inference_at, settings) and adds a "block" record.
"sols" follows the version-4 multi-visit form: a list of [first, last] ranges, the longest visit first
(it names the folder: mars2020_sol_<first sol>_<key>_colmap); every listed visit is selected."""
import json, re, sys, numpy as np
from sitesdef import P, X, Y, S, F, HALF, fmt_runs, fmt_counts
from dem import LocalFrame
from refdata import PANOS
out_path = sys.argv[1] if len(sys.argv) > 1 else 'sites_blocks.json'
blocks = json.load(open('sites_zoom.json'))
legacy = json.load(open('sites.json'))['sites']            # the sites file the blocks were built from
LF = LocalFrame(P)
E = np.where(F == 'y')[0]
REGION = {}
REGIONS = {'crater_rim_west': ('cluster21', 'cluster22', 'groloy', 'cluster23', 'marble_mountain'),
           'crater_rim': ('cluster16', 'cluster17', 'cluster18', 'cluster19'),
           'margin_unit_neretva_vallis': ('cluster13', 'overlook_mountain', 'bright_angle', 'cluster14', 'plateau_point', 'cluster15', 'rio_chiquito'),
           'upper_fan_belva': ('tenby_berea', 'cluster11', 'wild_basin_lake', 'cluster12', 'airey_hill'),
           'delta_front': ('cluster10', 'threeforks_north', 'cluster6', 'cluster7', 'cluster8', 'cluster9'),
           'crater_floor_seitah': ('cluster1', 'cluster2', 'chal_rocks_large', 'cluster3', 'rochette', 'cluster4', 'cluster5')}
for r, ks in REGIONS.items():
    for k in ks: REGION[k] = r
def slug(name): return re.sub(r'[^a-z0-9]+', '_', name.lower()).strip('_')
def eod_in_square(o):
    return [int(S[i]) for i in E if abs(X[i]-o['cx']) <= HALF and abs(Y[i]-o['cy']) <= HALF]
def legacy_match(o, sols):
    """sites.json entry whose sol window holds the most of this block's end-of-drive sols (ties: the narrower window)."""
    best, bscore = None, (0, 0)
    for k, v in legacy.items():
        rngs = v['sols'] if isinstance(v['sols'][0], list) else [v['sols']]
        n = sum(any(a <= s <= b for a, b in rngs) for s in sols)
        width = sum(b - a for a, b in rngs)
        if n and (n, -width) > bscore: best, bscore = k, (n, -width)
    return best
sites_out, groups = {}, {'blocks_all': []}
for o in blocks:
    key = f"blk{o['id']:02d}_{slug(o['name'])}"
    sols = eod_in_square(o)
    src = o['key'] if o['key'] in legacy else legacy_match(o, sols)
    runs = sorted(o['runs'], key=lambda r: (-(r[1]-r[0]), r[0]))        # longest visit first
    lon, lat = LF.to_lonlat(o['cx'], o['cy'])
    kind = 'cluster' if o['key'].startswith('cluster') else ('sites.json' if o['key'] in legacy else 'sol window')
    note = (f"Block {o['id']} ({fmt_counts(o)}): " + {'cluster': '≥4 end-of-drive Navcam 360s chained at ≤10 m',
            'sites.json': f"from sites.json '{o['key']}'", 'sol window': 'user-defined sol window'}[kind]
            + f"; centre ±{HALF:.0f} m; visits {fmt_runs(o['runs'])}")
    sites_out[key] = {
        'sols': [list(r) for r in runs],
        'label': o['name'],
        'zcam': list(legacy[src]['zcam']) if src and 'zcam' in legacy[src] else [],
        'note': note,
        'no_mask_inference_at': list(legacy[src].get('no_mask_inference_at', [])) if src == o['key'] else [],
        'settings': {},
        'block': {
            'number': o['id'], 'name': o['name'], 'region': REGION.get(o['key'], ''), 'kind': kind,
            'source_key': o['key'], 'legacy_site': src,
            'centre': {'lon': round(float(lon), 7), 'lat': round(float(lat), 7),
                       'easting': round(o['cx'], 2), 'northing': round(o['cy'], 2), 'frame': 'M20_waypoints easting/northing'},
            'half_size_m': HALF,
            'visits': [list(r) for r in o['runs']],
            'end_of_drive_sols': sols,
            'n_navcam_360': o['n360'], 'n_partial_navcam': o['npart'],
            'mastcam_z_360': o.get('zpanos', []),
        }}
    groups['blocks_all'].append(key)
    groups.setdefault('blocks_' + REGION.get(o['key'], 'other'), []).append(key)
doc = {
  '_about': ('Blocks of rover stations (M2020 Navcam end-of-drive 360s), numbered by first sol. Generated by export_sites.py from '
             'M20_waypoints (sols %d-%d). "sols" is a list of visits [first, last] (longest first; the first names the folder). '
             '"block" holds the geometry: centre (lon/lat and waypoint easting/northing), half_size_m, the end-of-drive sols inside the square, '
             'the Navcam 360 count and the numbered Mastcam-Z 360s. "zcam" is copied from the matching legacy sites.json entry ("legacy_site"), '
             'otherwise empty (Navcam only). Use as notebook 03 SITES_EXTRA or merge into src/mppp/data/sites.json.') % (S.min(), S.max()),
  'version': 4,
  'sites': sites_out,
  'groups': groups,
}
json.dump(doc, open(out_path, 'w'), indent=1, ensure_ascii=False)
print('wrote', out_path, len(sites_out), 'blocks;', ', '.join(f"{k}: {len(v)}" for k, v in groups.items()))
